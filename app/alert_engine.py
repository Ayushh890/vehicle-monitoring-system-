class AlertEngine:
    """Configurable rule-based alert engine.

    Generates alerts based on observed conditions with proper
    machine-readable reasons and confidence scores.
    """

    def __init__(self, db_session, user_id: int):
        self.db_session = db_session
        self.user_id = user_id
        self.rules: Dict[str, Dict[str, Any]] = {}
        self._register_default_rules()

    def _register_default_rules(self) -> None:
        """Register the 8 configurable alert rules specified in the prompt."""
        # 1. Authorized watchlist vehicle detection
        self.register_rule(
            "watchlist_match",
            self._check_watchlist_match,
            severity="HIGH",
            description="Authorized watchlist vehicle detected",
        )

        # 2. Camera offline
        self.register_rule(
            "camera_offline",
            self._check_camera_offline,
            severity="HIGH",
            description="Camera has been offline beyond threshold",
        )

        # 3. Camera degraded
        self.register_rule(
            "camera_degraded",
            self._check_camera_degraded,
            severity="MEDIUM",
            description="Camera frame quality below acceptable threshold",
        )

        # 4. Severe congestion
        self.register_rule(
            "severe_congestion",
            self._check_severe_congestion,
            severity="HIGH",
            description="Traffic congestion exceeds threshold",
        )

        # 5. Traffic spike
        self.register_rule(
            "traffic_spike",
            self._check_traffic_spike,
            severity="MEDIUM",
            description="Sudden increase in vehicle count",
        )

        # 6. Travel-time anomaly
        self.register_rule(
            "travel_time_anomaly",
            self._check_travel_time_anomaly,
            severity="HIGH",
            description="Travel time deviates from baseline",
        )

        # 7. Physically impossible trajectory
        self.register_rule(
            "impossible_trajectory",
            self._check_impossible_trajectory,
            severity="HIGH",
            description="Vehicle trajectory violates physical constraints",
        )

        # 8. OCR quality degradation
        self.register_rule(
            "ocr_quality_degradation",
            self._check_ocr_quality_degradation,
            severity="LOW",
            description="OCR confidence below acceptable threshold",
        )

    def register_rule(
        self,
        rule_name: str,
        check_func,
        severity: str,
        description: str,
    ) -> None:
        """Register a new alert rule.

        Args:
            rule_name: Unique rule identifier
            check_func: Async function that returns alert dict or None
            severity: Alert severity level
            description: Human-readable description
        """
        self.rules[rule_name] = {
            "check_func": check_func,
            "severity": severity,
            "description": description,
            "enabled": True,
        }

    def check_all_rules(self, context: Dict[str, Any]) -> List[Dict[str, Any]]:
        """Run all registered rules against the given context.

        Args:
            context: Dict with relevant data (camera_id, frame, tracks, etc.)

        Returns:
            List of generated alerts (empty if none)
        """
        alerts = []
        for rule_name, rule in self.rules.items():
            if not rule["enabled"]:
                continue

            try:
                alert = rule["check_func"](context)
                if alert is not None:
                    alert["_rule_name"] = rule_name
                    alert["_rule_description"] = rule["description"]
                    alerts.append(alert)
            except Exception as e:
                # Log error but don't crash the pipeline
                import logging
                logging.getLogger(__name__).error(
                    f"Alert rule '{rule_name}' error: {e}"
                )

        return alerts

    # ---- Individual rule implementations ----

    def _check_watchlist_match(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 1: Authorized watchlist vehicle detection.

        Matches vehicle plates against the authorized watchlist.
        Does NOT label vehicles as 'suspicious' merely because AI is uncertain.

        Args:
            context: Must contain 'plate_read', 'camera_id', 'global_vehicles'

        Returns:
            Alert dict if watchlist match found, None otherwise
        """
        from backend.app.models import Watchlist, GlobalVehicle

        plate_read = context.get("plate_read")
        camera_id = context.get("camera_id")
        global_vehicles = context.get("global_vehicles", {})

        if not plate_read or not camera_id:
            return None

        raw_text = plate_read.normalized_text or plate_read.raw_text
        if not raw_text:
            return None

        # Search watchlist for this plate
        watchlist_entries = (
            self.db_session.query(Watchlist)
            .filter(Watchplate.plate.ilike(raw_text))
            .all()
        )

        if not watchlist_entries:
            return None

        # Find matching global vehicle(s)
        matched_vehicles = []
        for w_entry in watchlist_entries:
            gv = global_vehicles.get(w_entry.plate)
            if gv:
                matched_vehicles.append(gv)

        if not matched_vehicles:
            # Plate matches watchlist but no global vehicle found yet
            # Create alert referencing the watchlist entry
            return {
                "alert_type": AlertType.WATCHLIST_MATCH.value,
                "severity": AlertSeverity.HIGH.value,
                "camera_id": camera_id,
                "reason": f"watchlist_plate_match:{watchlist_entries[0].id}",
                "confidence": 0.8,
                "evidence_reference": f"plate_read:{plate_read.id}",
                "watchlist_entry_id": watchlist_entries[0].id,
            }

        # Multiple matches - return the best one
        best_match = matched_vehicles[0]
        return {
            "alert_type": AlertType.WATCHLIST_MATCH.value,
            "severity": AlertSeverity.HIGH.value,
            "camera_id": camera_id,
            "global_vehicle_id": best_match.id,
            "reason": f"watchlist_plate_match:{matched_vehicles[0].vehicle_id}",
            "confidence": 0.9,
            "evidence_reference": f"plate_read:{plate_read.id},global_vehicle:{best_match.id}",
        }

    def _check_camera_offline(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 2: Camera offline detection.

        Args:
            context: Must contain 'camera' and 'last_frame_at'

        Returns:
            Alert if camera offline, None otherwise
        """
        from backend.app.models import Camera

        camera = context.get("camera")
        if not camera:
            return None

        # Check if camera has been offline (no recent frames)
        from datetime import datetime

        if camera.last_frame_at:
            time_since_last = (datetime.utcnow() - camera.last_frame_at).total_seconds()
            # Offline threshold: 5 minutes without a frame
            if time_since_last > 300:
                return {
                    "alert_type": AlertType.CAMERA_OFFLINE.value,
                    "severity": AlertSeverity.HIGH.value,
                    "camera_id": camera.id,
                    "reason": "camera_offline:300s",
                    "confidence": 0.95,
                    "evidence_reference": f"camera:{camera.id},last_frame:{camera.last_frame_at.isoformat() if hasattr(camera.last_frame_at, 'isoformat') else str(camera.last_frame_at)}",
                }

        return None

    def _check_camera_degraded(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 3: Camera degraded quality detection.

        Args:
            context: Must contain 'camera' with quality metrics

        Returns:
            Alert if degraded, None otherwise
        """
        from backend.app.models import Camera

        camera = context.get("camera")
        if not camera:
            return None

        # Check if frame quality is below threshold
        # Confidence below 0.6 or resolution below minimum
        if camera.avg_frame_confidence is not None and camera.avg_frame_confidence < 0.6:
            return {
                "alert_type": AlertType.CAMERA_DEGRADED.value,
                "severity": AlertSeverity.MEDIUM.value,
                "camera_id": camera.id,
                "reason": "camera_degraded:confidence_low",
                "confidence": 0.8,
                "evidence_reference": f"camera:{camera.id},avg_confidence:{camera.avg_frame_confidence}",
            }

        # Check resolution
        if camera.avg_frame_resolution:
            width, height = camera.avg_frame_resolution
            if width < 640 or height < 480:
                return {
                    "alert_type": AlertType.CAMERA_DEGRADED.value,
                    "severity": AlertSeverity.MEDIUM.value,
                    "camera_id": camera.id,
                    "reason": "camera_degraded:resolution_low",
                    "confidence": 0.85,
                    "evidence_reference": f"camera:{camera.id},resolution:{width}x{height}",
                }

        return None

    def _check_severe_congestion(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 4: Severe congestion detection.

        Args:
            context: Must contain 'vehicle_count', 'threshold'

        Returns:
            Alert if severe congestion, None otherwise
        """
        vehicle_count = context.get("vehicle_count", 0)
        threshold = context.get("threshold", 50)  # Default: 50 vehicles

        if vehicle_count >= threshold:
            # Determine severity based on how much threshold is exceeded
            ratio = vehicle_count / threshold
            if ratio >= 2.0:
                severity = AlertSeverity.CRITICAL.value
            elif ratio >= 1.5:
                severity = AlertSeverity.HIGH.value
            else:
                severity = AlertSeverity.MEDIUM.value
        else:
                return None

        return {
                "alert_type": AlertType.SEVERE_CONGESTION.value,
                "severity": severity,
                "camera_id": context.get("camera_id"),
                "reason": f"severe_congestion:{vehicle_count}vehicles>={threshold}threshold",
                "confidence": 0.9,
                "evidence_reference": f"camera:{context.get('camera_id')},count:{vehicle_count}",
        }


    def _check_traffic_spike(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 5: Traffic spike detection.

        Compares current vehicle count to historical baseline.

        Args:
            context: Must contain 'current_count', 'baseline_count', 'spike_threshold'

        Returns:
            Alert if spike detected, None otherwise
        """
        current_count = context.get("current_count", 0)
        baseline_count = context.get("baseline_count", 0)
        spike_threshold = context.get("spike_threshold", 1.5)  # 1.5x increase

        if baseline_count > 0:
            ratio = current_count / baseline_count
            if ratio >= spike_threshold:
                # Determine severity
                if ratio >= 3.0:
                    severity = AlertSeverity.HIGH.value
                else:
                    severity = AlertSeverity.MEDIUM.value

                pct_increase = (ratio - 1) * 100
                return {
                    "alert_type": AlertType.TRAFFIC_SPIKE.value,
                    "severity": severity,
                    "camera_id": context.get("camera_id"),
                    "reason": f"traffic_spike:{pct_increase:.0f}pct_increase:{current_count}>{baseline_count}",
                    "confidence": 0.85,
                    "evidence_reference": f"camera:{context.get('camera_id')},current:{current_count},baseline:{baseline_count}",
                }

        return None

    def _check_travel_time_anomaly(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 6: Travel-time anomaly detection.

        Args:
            context: Must contain 'current_travel_time', 'baseline' dict

        Returns:
            Alert if anomaly, None otherwise
        """
        current_tt = context.get("current_travel_time")
        baseline = context.get("baseline")

        if current_tt is None or baseline is None:
            return None

        avg_baseline = baseline.get("average_minutes")
        if avg_baseline is None:
            return None

        difference = current_tt - avg_baseline
        # Anomaly if current exceeds baseline by more than 50%
        if difference > avg_baseline * 0.5:
            pct_change = (difference / avg_baseline) * 100
            severity = AlertSeverity.HIGH.value if pct_change > 100 else AlertSeverity.MEDIUM.value

            return {
                "alert_type": AlertType.TRAVEL_TIME_ANOMALY.value,
                "severity": severity,
                "camera_id": context.get("camera_id"),
                "global_vehicle_id": context.get("global_vehicle_id"),
                "reason": f"travel_time_anomaly:{pct_change:.1f}pct_increase:{current_tt}min>({avg_baseline}min)baseline",
                "confidence": 0.88,
                "evidence_reference": f"current:{current_tt}min,baseline:{avg_baseline}min,{context.get('reason', '')}",
            }

        return None

