class Alert(Base):
    """Real-time alert generated by the system.

    Every alert contains an explicit machine-readable reason
    and tracks its lifecycle status.
    """

    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True)
    alert_type = Column(String(50), nullable=False)
    severity = Column(String(20), nullable=False)
    timestamp = Column(DateTime(timezone=True), nullable=False, default=lambda: datetime.utcnow())
    camera_id = Column(Integer, ForeignKey("cameras.id"), nullable=True)
    global_vehicle_id = Column(Integer, ForeignKey("global_vehicles.id"), nullable=True)
    reason = Column(Text, nullable=False)  # Machine-readable reason string
    confidence = Column(Float, nullable=False, default=0.5)  # 0.0 to 1.0
    evidence_reference = Column(String(200), nullable=True)  # Reference to frame_id, track_id, etc.
    status = Column(String(20), nullable=False, default="NEW")

    # Relationships
    camera = relationship("Camera", back_populates="alerts")
    global_vehicle = relationship("GlobalVehicle", back_populates="alerts")

    __table_args__ = (
        Index("ix_alerts_status", "status"),
        Index("ix_alerts_camera_id", "camera_id"),
        Index("ix_alerts_global_vehicle_id", "global_vehicle_id"),
        Index("ix_alerts_timestamp", "timestamp"),
        Index("ix_alerts_alert_type", "alert_type"),
        CheckConstraint(
            "severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')",
            name="chk_alert_severity",
        ),
        CheckConstraint(
            "status IN ('NEW', 'ACKNOWLEDGED', 'RESOLVED')",
            name="chk_alert_status",
        ),
        CheckConstraint(
            "confidence >= 0.0 AND confidence <= 1.0",
            name="chk_alert_confidence",
        ),
    )


class Watchlist(Base):
    """Authorized watchlist for vehicle plates/identifiers.

    All watchlist actions are audited through the audit_logs table.
    """

    __tablename__ = "watchlist"

    id = Column(Integer, primary_key=True)
    plate = Column(String(50), nullable=False, unique=True)
    description = Column(Text, nullable=True)
    priority = Column(String(20), default="NORMAL")  # NORMAL, HIGH, CRITICAL
    active = Column(Boolean, default=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=lambda: datetime.utcnow())
    created_by = Column(Integer, ForeignKey("users.id"), nullable=True)

    # Relationships
    creator = relationship("User", back_populates="watchlist_entries")
    alerts = relationship("Alert", back_populates="watchlist_reference", cascade="all, delete-orphan")


