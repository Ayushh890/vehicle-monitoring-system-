    def _check_ocr_quality_degradation(self, context: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        """Rule 8: OCR quality degradation detection.

        Args:
            context: Must contain 'plate_read' with confidence

        Returns:
            Alert if OCR quality degraded, None otherwise
        """
        plate_read = context.get("plate_read")
        if not plate_read:
            return None

        confidence = plate_read.ocr_confidence
        # Degraded if confidence below 0.5
        if confidence < 0.5:
            return {
                "alert_type": AlertType.OCR_QUALITY_DEGRADATION.value,
                "severity": AlertSeverity.LOW.value,
                "camera_id": plate_read.camera_id,
                "reason": f"ocr_quality_degradation:confidence_{confidence:.2f}",
                "confidence": 0.7,
                "evidence_reference": f"plate_read:{plate_read.id},raw:{plate_read.raw_text},norm:{plate_read.normalized_text}",
            }

        return None